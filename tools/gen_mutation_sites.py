def render_site(cell_id: str) -> str:
    c = CELLS[cell_id]
    html = _PAGE
    for tok, val in {
        "__CELL__": cell_id,
        "__PRE_FORM__": c["pre_form"],
        "__INPUT__": c["input"],
        "__BUTTON__": c["button"],
        "__DELAY__": str(c["delay_ms"]),
        "__FAIL_FIRST__": "true" if c["fail_first"] else "false",
        "__REBUILD__": "true" if c["rebuild_on_input"] else "false",
        "__SWAP__": "true" if c["swap_button_on_input"] else "false",
    }.items():
        html = html.replace(tok, val)
    return html


def manifest() -> dict:
    return {
        "generated_by": "tools/gen_mutation_sites.py",
        "basis": "StressWeb (arxiv 2604.16385) axes x intensity + clean reference; "
                 "WebArena too-clean-environment flaw (arxiv 2407.01502)",
        "determinism": "no Math.random; attempt-counter fault schedule; input-event-anchored "
                       "mutations (setTimeout 0), not timer races",
        "heldout_note": "cells derive only from the v1-style clean template; the held-out "
                        "mock site is never read (locked by test)",
        "cells": {
            cid: {k: c[k] for k in ("axis", "level", "level_name", "perturbations",
                                    "design_intent", "recoverable_in_principle")}
            for cid, c in CELLS.items()
        },
    }


def generate() -> None:
    for cell_id in CELLS:
        d = OUT / cell_id
        d.mkdir(parents=True, exist_ok=True)
        with open(d / "index.html", "w", encoding="utf-8", newline="\n") as fh:
            fh.write(render_site(cell_id))
    with open(OUT / "manifest.json", "w", encoding="utf-8", newline="\n") as fh:
        json.dump(manifest(), fh, indent=2, ensure_ascii=False)


if __name__ == "__main__":
    generate()
    print(f"wrote {len(CELLS)} cells + manifest.json under {OUT}")
