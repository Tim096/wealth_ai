_INPUT_CLEAN = ('<input id="search-box" name="q" type="text" placeholder="Search products" '
                'aria-label="Search products" data-sb="1">')
_BUTTON_CLEAN = '<button id="search-btn" type="submit">Search</button>'


def _cell(axis: str, level: int, level_name: str, *, pre_form: str = "",
          input_html: str = _INPUT_CLEAN, button_html: str = _BUTTON_CLEAN,
          delay_ms: int = 0, fail_first: bool = False, rebuild_on_input: bool = False,
          swap_button_on_input: bool = False, perturbations: list[str] | None = None,
          design_intent: str = "", recoverable_in_principle: str = "") -> dict:
    return {
        "axis": axis, "level": level, "level_name": level_name,
        "pre_form": pre_form, "input": input_html, "button": button_html,
        "delay_ms": delay_ms, "fail_first": fail_first,
        "rebuild_on_input": rebuild_on_input, "swap_button_on_input": swap_button_on_input,
        "perturbations": perturbations or [],
        "design_intent": design_intent,
        "recoverable_in_principle": recoverable_in_principle,
    }


